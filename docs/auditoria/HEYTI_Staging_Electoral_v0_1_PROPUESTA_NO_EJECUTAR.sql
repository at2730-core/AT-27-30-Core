BEGIN;
CREATE SCHEMA IF NOT EXISTS electoral_stage;

CREATE TABLE IF NOT EXISTS electoral_stage.source_release (
    release_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    authority text NOT NULL,
    source_name text NOT NULL,
    source_uri text,
    acquired_at timestamptz,
    published_at timestamptz,
    cut_label text NOT NULL,
    outer_zip_sha256 char(64) NOT NULL CHECK (outer_zip_sha256 ~ '^[0-9a-fA-F]{64}$'),
    certification_status text NOT NULL DEFAULT 'UNREVIEWED',
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (outer_zip_sha256, cut_label)
);

CREATE TABLE IF NOT EXISTS electoral_stage.source_member (
    member_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    release_id bigint NOT NULL REFERENCES electoral_stage.source_release(release_id),
    member_path text NOT NULL,
    member_sha256 char(64) NOT NULL CHECK (member_sha256 ~ '^[0-9a-fA-F]{64}$'),
    encoding_name text,
    delimiter_char text CHECK (delimiter_char IS NULL OR length(delimiter_char) = 1),
    expected_rows bigint CHECK (expected_rows IS NULL OR expected_rows >= 0),
    header_columns jsonb NOT NULL CHECK (jsonb_typeof(header_columns) = 'array'),
    UNIQUE (release_id, member_path)
);

CREATE TABLE IF NOT EXISTS electoral_stage.election_series (
    series_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id bigint NOT NULL REFERENCES electoral_stage.source_member(member_id),
    election_year smallint NOT NULL CHECK (election_year IN (2018, 2021, 2024)),
    election_type text NOT NULL CHECK (election_type IN ('A','DF','DL','G','P','S')),
    modality text NOT NULL CHECK (modality IN ('MR','RP','UNICA')),
    geography text NOT NULL DEFAULT 'GTO',
    aggregation_level text NOT NULL CHECK (aggregation_level IN ('SECTION','ACTA','MUNICIPAL')),
    judicial_cut text NOT NULL DEFAULT 'SOURCE_AS_PUBLISHED',
    selection_status text NOT NULL DEFAULT 'UNREVIEWED',
    UNIQUE (member_id, election_year, election_type, modality, geography, aggregation_level, judicial_cut),
    UNIQUE (member_id, series_id)
);

-- Registro literal de cada fila. El hash evita confundir un reordenamiento
-- de filas con una actualización silenciosa, y raw_cells conserva el texto.
CREATE TABLE IF NOT EXISTS electoral_stage.raw_row (
    raw_row_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id bigint NOT NULL REFERENCES electoral_stage.source_member(member_id),
    source_line bigint NOT NULL CHECK (source_line >= 2),
    raw_cells jsonb NOT NULL CHECK (jsonb_typeof(raw_cells) = 'object'),
    raw_line_sha256 char(64) NOT NULL CHECK (raw_line_sha256 ~ '^[0-9a-fA-F]{64}$'),
    UNIQUE (member_id, source_line),
    UNIQUE (member_id, raw_row_id)
);

-- La clave de unidad es opaca y se construye con los campos de identidad
-- fuente pertinentes para cada serie. Nunca es solo el número de sección.
CREATE TABLE IF NOT EXISTS electoral_stage.computation_unit (
    unit_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    series_id bigint NOT NULL REFERENCES electoral_stage.election_series(series_id),
    unit_key text NOT NULL,
    unit_kind text NOT NULL CHECK (unit_kind IN ('ORDINARY_SECTION','SPECIAL_AGGREGATE','SPECIAL_SECTION_ROW','SPECIAL_ACTA','MUNICIPAL_ROW','OTHER')),
    section_code text,
    state_code text,
    district_federal_code text,
    district_local_code text,
    municipality_code text,
    original_identity jsonb NOT NULL CHECK (jsonb_typeof(original_identity) = 'object'),
    territorial_section_id bigint NULL REFERENCES territorial.section(section_id),
    territorial_status text NOT NULL DEFAULT 'UNREVIEWED',
    genealogy_status text NOT NULL DEFAULT 'UNRESOLVED',
    CHECK (unit_kind <> 'ORDINARY_SECTION' OR section_code IS NOT NULL),
    CHECK (unit_kind <> 'MUNICIPAL_ROW' OR municipality_code IS NOT NULL),
    UNIQUE (series_id, unit_key),
    UNIQUE (series_id, unit_id)
);

CREATE TABLE IF NOT EXISTS electoral_stage.option_column (
    option_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    series_id bigint NOT NULL REFERENCES electoral_stage.election_series(series_id),
    literal_header text NOT NULL,
    column_ordinal integer NOT NULL CHECK (column_ordinal >= 1),
    option_type text NOT NULL DEFAULT 'UNCLASSIFIED'
       CHECK (option_type IN ('UNCLASSIFIED','PARTY','COALITION_COMBINATION','INDEPENDENT',
                             'WRITE_IN','NULL_VOTE','VALID_VOTE_TOTAL','OTHER')),
    candidacy_ref text,
    classification_evidence text,
    UNIQUE (series_id, column_ordinal),
    UNIQUE (series_id, option_id)
);

-- Una fila de total por unidad agregada y corte; ausencia conserva NULL.
CREATE TABLE IF NOT EXISTS electoral_stage.section_tally (
    tally_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    series_id bigint NOT NULL,
    member_id bigint NOT NULL,
    unit_id bigint NOT NULL UNIQUE,
    FOREIGN KEY (series_id, unit_id) REFERENCES electoral_stage.computation_unit(series_id, unit_id),
    FOREIGN KEY (member_id, series_id) REFERENCES electoral_stage.election_series(member_id, series_id),
    raw_row_id bigint NOT NULL,
    FOREIGN KEY (member_id, raw_row_id) REFERENCES electoral_stage.raw_row(member_id, raw_row_id),
    total_votes bigint CHECK (total_votes IS NULL OR total_votes >= 0),
    nominal_list bigint CHECK (nominal_list IS NULL OR nominal_list >= 0),
    total_raw text,
    nominal_raw text,
    total_truth_status text NOT NULL DEFAULT 'UNREVIEWED',
    nominal_truth_status text NOT NULL DEFAULT 'UNREVIEWED',
    total_cause text,
    nominal_cause text,
    CHECK (total_votes IS NOT NULL OR total_cause IS NOT NULL),
    CHECK (nominal_list IS NOT NULL OR nominal_cause IS NOT NULL),
    UNIQUE (series_id, tally_id)
);

CREATE TABLE IF NOT EXISTS electoral_stage.option_vote (
    series_id bigint NOT NULL,
    tally_id bigint NOT NULL,
    option_id bigint NOT NULL,
    FOREIGN KEY (series_id, tally_id) REFERENCES electoral_stage.section_tally(series_id, tally_id),
    FOREIGN KEY (series_id, option_id) REFERENCES electoral_stage.option_column(series_id, option_id),
    votes bigint CHECK (votes IS NULL OR votes >= 0),
    raw_value text,
    truth_status text NOT NULL DEFAULT 'UNREVIEWED',
    missing_cause text,
    PRIMARY KEY (tally_id, option_id),
    CHECK (votes IS NOT NULL OR missing_cause IS NOT NULL)
);

-- Actas y decisiones judiciales se conservan como evidencia vinculable;
-- no se suman actas por defecto ni se sobreescribe una versión con otra.
CREATE TABLE IF NOT EXISTS electoral_stage.acta_evidence (
    acta_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    series_id bigint NOT NULL,
    member_id bigint NOT NULL,
    FOREIGN KEY (member_id, series_id) REFERENCES electoral_stage.election_series(member_id, series_id),
    unit_id bigint,
    FOREIGN KEY (series_id, unit_id) REFERENCES electoral_stage.computation_unit(series_id, unit_id),
    raw_row_id bigint NOT NULL,
    FOREIGN KEY (member_id, raw_row_id) REFERENCES electoral_stage.raw_row(member_id, raw_row_id),
    acta_key text,
    casilla_key text,
    judicial_status text,
    original_identity jsonb NOT NULL CHECK (jsonb_typeof(original_identity) = 'object'),
    UNIQUE (series_id, raw_row_id)
);

CREATE TABLE IF NOT EXISTS electoral_stage.audit_run (
    run_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    release_id bigint NOT NULL REFERENCES electoral_stage.source_release(release_id),
    importer_version text NOT NULL,
    manifest_sha256 char(64) NOT NULL CHECK (manifest_sha256 ~ '^[0-9a-fA-F]{64}$'),
    started_at timestamptz NOT NULL DEFAULT now(),
    finished_at timestamptz,
    status text NOT NULL DEFAULT 'RUNNING',
    metrics jsonb NOT NULL DEFAULT '{}'::jsonb,
    UNIQUE (release_id, importer_version, manifest_sha256)
);

CREATE TABLE IF NOT EXISTS electoral_stage.reconciliation_issue (
    issue_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id bigint NOT NULL REFERENCES electoral_stage.audit_run(run_id),
    series_id bigint REFERENCES electoral_stage.election_series(series_id),
    unit_id bigint REFERENCES electoral_stage.computation_unit(unit_id),
    issue_code text NOT NULL,
    field_name text,
    expected_value text,
    observed_value text,
    evidence jsonb NOT NULL DEFAULT '{}'::jsonb,
    resolution_status text NOT NULL DEFAULT 'OPEN',
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS es_series_election_idx ON electoral_stage.election_series(election_year,election_type,modality);
CREATE INDEX IF NOT EXISTS es_unit_section_idx ON electoral_stage.computation_unit(series_id,section_code) WHERE unit_kind='ORDINARY_SECTION';
CREATE INDEX IF NOT EXISTS es_unit_current_idx ON electoral_stage.computation_unit(territorial_section_id) WHERE territorial_section_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS es_issue_run_idx ON electoral_stage.reconciliation_issue(run_id, resolution_status);
COMMIT;
