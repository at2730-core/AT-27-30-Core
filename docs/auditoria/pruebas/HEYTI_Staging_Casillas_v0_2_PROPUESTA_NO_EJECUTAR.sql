-- HEYTI v0.2: extensión CAS del staging v0.1.
-- SOLO ensayo en base temporal después de v0.1. NO EJECUTAR EN at2730_core.
BEGIN;
ALTER TABLE electoral_stage.source_member
    ADD CONSTRAINT es_member_release_member_uq UNIQUE (release_id, member_id);

CREATE TABLE electoral_stage.series_cas_member (
    series_id bigint NOT NULL,
    release_id bigint NOT NULL,
    section_member_id bigint NOT NULL,
    cas_member_id bigint NOT NULL,
    FOREIGN KEY (section_member_id, series_id)
        REFERENCES electoral_stage.election_series(member_id, series_id),
    FOREIGN KEY (release_id, section_member_id)
        REFERENCES electoral_stage.source_member(release_id, member_id),
    FOREIGN KEY (release_id, cas_member_id)
        REFERENCES electoral_stage.source_member(release_id, member_id),
    CHECK (section_member_id <> cas_member_id),
    PRIMARY KEY (series_id, cas_member_id),
    UNIQUE (series_id)
);

CREATE TABLE electoral_stage.casilla_tally (
    casilla_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    series_id bigint NOT NULL,
    cas_member_id bigint NOT NULL,
    unit_id bigint NOT NULL,
    raw_row_id bigint NOT NULL,
    casilla_key text NOT NULL,
    original_identity jsonb NOT NULL CHECK (jsonb_typeof(original_identity) = 'object'),
    total_votes bigint CHECK (total_votes IS NULL OR total_votes >= 0),
    total_raw text,
    nominal_list bigint CHECK (nominal_list IS NULL OR nominal_list >= 0),
    nominal_raw text,
    estatus_acta text,
    tribunal text,
    juicio text,
    observaciones text,
    ruta_acta text,
    FOREIGN KEY (series_id, cas_member_id)
        REFERENCES electoral_stage.series_cas_member(series_id, cas_member_id),
    FOREIGN KEY (cas_member_id, raw_row_id)
        REFERENCES electoral_stage.raw_row(member_id, raw_row_id),
    FOREIGN KEY (series_id, unit_id)
        REFERENCES electoral_stage.computation_unit(series_id, unit_id),
    UNIQUE (series_id, casilla_id),
    UNIQUE (series_id, cas_member_id, raw_row_id),
    UNIQUE (series_id, casilla_key)
);

CREATE TABLE electoral_stage.casilla_option_vote (
    series_id bigint NOT NULL,
    casilla_id bigint NOT NULL,
    option_id bigint NOT NULL,
    votes bigint CHECK (votes IS NULL OR votes >= 0),
    raw_value text,
    missing_cause text,
    FOREIGN KEY (series_id, casilla_id)
        REFERENCES electoral_stage.casilla_tally(series_id, casilla_id),
    FOREIGN KEY (series_id, option_id)
        REFERENCES electoral_stage.option_column(series_id, option_id),
    PRIMARY KEY (casilla_id, option_id),
    CHECK (votes IS NOT NULL OR missing_cause IS NOT NULL)
);
CREATE INDEX es_casilla_unit_idx ON electoral_stage.casilla_tally(series_id, unit_id);
COMMIT;
