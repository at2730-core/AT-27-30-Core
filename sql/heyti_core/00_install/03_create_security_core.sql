CREATE TABLE audit.authorization_event (
    audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    user_id BIGINT,
    session_id VARCHAR(160),
    permission_code VARCHAR(80) NOT NULL,
    resource_type VARCHAR(80) NOT NULL,
    resource_ref VARCHAR(200),
    decision VARCHAR(20) NOT NULL,
    reason_code VARCHAR(80) NOT NULL,
    scope_id BIGINT,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT authorization_event_user_fkey
        FOREIGN KEY (user_id)
        REFERENCES security.app_user (user_id)
        ON DELETE RESTRICT,
    CONSTRAINT authorization_event_scope_fkey
        FOREIGN KEY (scope_id)
        REFERENCES security.territorial_scope (scope_id)
        ON DELETE RESTRICT,
    CONSTRAINT authorization_event_decision_check
        CHECK (
            decision IN (
                'AUTHORIZED',
                'DENIED'
            )
        ),
    CONSTRAINT authorization_event_metadata_object_check
        CHECK (jsonb_typeof(metadata) = 'object')
);

CREATE INDEX idx_audit_authorization_occurred
    ON audit.authorization_event (occurred_at);

CREATE INDEX idx_audit_authorization_user
    ON audit.authorization_event (user_id, occurred_at);

CREATE INDEX idx_audit_authorization_permission
    ON audit.authorization_event (permission_code, occurred_at);

