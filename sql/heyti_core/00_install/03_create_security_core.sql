    role_id,
    permission_id,
    permission_scope
)
SELECT
    r.role_id,
    p.permission_id,
    'GLOBAL'
FROM security.access_role r
CROSS JOIN security.access_permission p
WHERE r.role_code = 'ADMINISTRATOR';

INSERT INTO security.role_permission (
    role_id,
    permission_id,
    permission_scope
)
SELECT
    r.role_id,
    p.permission_id,
    CASE
        WHEN p.permission_code IN (
            'FIELD_MODULE_ACCESS',
            'SECTION_READ',
            'UNIVERSE_CATALOG_READ',
            'UNIVERSE_MAP_READ',
            'FIELD_SUMMARY_READ',
            'FIELD_MAP_READ',
            'FIELD_RECORD_CREATE'
        )
        THEN 'ASSIGNED_TERRITORY'
        ELSE 'ASSIGNED_TEAM'
    END
FROM security.access_role r
JOIN security.access_permission p
  ON p.permission_code IN (
      'FIELD_MODULE_ACCESS',
      'SECTION_READ',
      'UNIVERSE_CATALOG_READ',
      'UNIVERSE_MAP_READ',
      'FIELD_SUMMARY_READ',
      'FIELD_MAP_READ',
      'FIELD_RECORD_READ',
      'FIELD_PERSONAL_DATA_READ',
      'FIELD_RECORD_CREATE',
      'FIELD_RECORD_UPDATE',
      'FIELD_LOCATION_UPDATE',
      'FIELD_ASSIGNMENT_MANAGE',
      'FIELD_EXPORT_REDACTED',
      'FIELD_AUDIT_READ'
  )
WHERE r.role_code = 'COORDINATOR';

INSERT INTO security.role_permission (
    role_id,
    permission_id,
    permission_scope
)
SELECT
    r.role_id,
    p.permission_id,
    CASE
        WHEN p.permission_code IN (
            'FIELD_MODULE_ACCESS',
            'FIELD_RECORD_CREATE'
        )
        THEN 'ASSIGNED_TERRITORY'
        WHEN p.permission_code = 'FIELD_AUDIT_READ'
        THEN 'OWN_ACTIVITY'
        ELSE 'OWN_RECORDS'
    END
FROM security.access_role r
JOIN security.access_permission p
  ON p.permission_code IN (
      'FIELD_MODULE_ACCESS',
      'FIELD_SUMMARY_READ',
      'FIELD_MAP_READ',
      'FIELD_RECORD_READ',
      'FIELD_PERSONAL_DATA_READ',
      'FIELD_RECORD_CREATE',
      'FIELD_RECORD_UPDATE',
      'FIELD_LOCATION_UPDATE',
      'FIELD_AUDIT_READ'
  )
WHERE r.role_code = 'PROMOTER';

