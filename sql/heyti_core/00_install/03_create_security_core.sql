CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE SCHEMA IF NOT EXISTS security;
CREATE SCHEMA IF NOT EXISTS audit;

CREATE TABLE security.app_user (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_uuid UUID NOT NULL DEFAULT gen_random_uuid(),
    username VARCHAR(100) NOT NULL,
    display_name VARCHAR(200) NOT NULL,
    external_identity VARCHAR(255),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deactivated_at TIMESTAMPTZ,
    CONSTRAINT app_user_uuid_key UNIQUE (user_uuid),
    CONSTRAINT app_user_username_not_blank
        CHECK (btrim(username) <> ''),
    CONSTRAINT app_user_display_name_not_blank
        CHECK (btrim(display_name) <> ''),
    CONSTRAINT app_user_deactivation_consistent
        CHECK (
            (
                active = TRUE
                AND deactivated_at IS NULL
            )
            OR
            (
                active = FALSE
                AND deactivated_at IS NOT NULL
            )
        )
);

CREATE UNIQUE INDEX ux_security_app_user_username
    ON security.app_user (lower(username));

CREATE UNIQUE INDEX ux_security_app_user_external_identity
    ON security.app_user (external_identity)
    WHERE external_identity IS NOT NULL;

CREATE TABLE security.user_credential (
    user_id BIGINT PRIMARY KEY,
    credential_hash TEXT NOT NULL,
    hash_algorithm VARCHAR(30) NOT NULL DEFAULT 'ARGON2ID',
    failed_attempts INTEGER NOT NULL DEFAULT 0,
    locked_until TIMESTAMPTZ,
    password_changed_at TIMESTAMPTZ NOT NULL
        DEFAULT CURRENT_TIMESTAMP,
    must_change BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT user_credential_user_fkey
        FOREIGN KEY (user_id)
        REFERENCES security.app_user (user_id)
        ON DELETE RESTRICT,
    CONSTRAINT user_credential_hash_not_blank
        CHECK (btrim(credential_hash) <> ''),
    CONSTRAINT user_credential_algorithm_check
        CHECK (hash_algorithm IN ('ARGON2ID')),
    CONSTRAINT user_credential_hash_format_check
        CHECK (credential_hash LIKE '$argon2id$%'),
    CONSTRAINT user_credential_failed_attempts_check
        CHECK (failed_attempts >= 0)
);

CREATE TABLE security.access_role (
    role_id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_code VARCHAR(40) NOT NULL,
    role_name VARCHAR(100) NOT NULL,
    description TEXT,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT access_role_code_key UNIQUE (role_code),
    CONSTRAINT access_role_code_check
        CHECK (
            role_code IN (
                'ADMINISTRATOR',
                'COORDINATOR',
                'PROMOTER'
            )
        )
);

CREATE TABLE security.access_permission (
    permission_id SMALLINT
        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    permission_code VARCHAR(80) NOT NULL,
    description TEXT NOT NULL,
    sensitive BOOLEAN NOT NULL DEFAULT FALSE,
    audit_required BOOLEAN NOT NULL DEFAULT FALSE,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT access_permission_code_key
        UNIQUE (permission_code),
    CONSTRAINT access_permission_code_not_blank
        CHECK (btrim(permission_code) <> '')
);

CREATE TABLE security.role_permission (
    role_id SMALLINT NOT NULL,
    permission_id SMALLINT NOT NULL,
    permission_scope VARCHAR(40) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (role_id, permission_id),
    CONSTRAINT role_permission_role_fkey
        FOREIGN KEY (role_id)
        REFERENCES security.access_role (role_id)
        ON DELETE RESTRICT,
    CONSTRAINT role_permission_permission_fkey
        FOREIGN KEY (permission_id)
        REFERENCES security.access_permission (permission_id)
        ON DELETE RESTRICT,
    CONSTRAINT role_permission_scope_check
        CHECK (
            permission_scope IN (
                'GLOBAL',
                'ASSIGNED_TERRITORY',
                'ASSIGNED_TEAM',
                'OWN_RECORDS',
                'OWN_ACTIVITY'
            )
        )
);

CREATE TABLE security.user_role_assignment (
