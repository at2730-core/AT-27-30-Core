        FOREIGN KEY (user_id)
        REFERENCES security.app_user (user_id)
        ON DELETE RESTRICT,
    CONSTRAINT user_role_role_fkey
        FOREIGN KEY (role_id)
        REFERENCES security.access_role (role_id)
        ON DELETE RESTRICT,
